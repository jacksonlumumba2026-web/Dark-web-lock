package com.darkweblock.app

import android.content.Context
import org.json.JSONObject

/** The owner's registration details, stored locally. Not sent anywhere. */
data class OwnerProfile(
    val ownerName: String = "",
    val contact: String = "",
    val deviceLabel: String = "",
) {
    val isRegistered: Boolean get() = ownerName.isNotBlank()
}

class OwnerStore(context: Context) {

    private val prefs = context.getSharedPreferences("dark_web_lock_owner", Context.MODE_PRIVATE)

    fun load(): OwnerProfile {
        val raw = prefs.getString(KEY, null) ?: return OwnerProfile()
        return runCatching {
            val o = JSONObject(raw)
            OwnerProfile(
                ownerName = o.optString("ownerName"),
                contact = o.optString("contact"),
                deviceLabel = o.optString("deviceLabel"),
            )
        }.getOrDefault(OwnerProfile())
    }

    fun save(profile: OwnerProfile) {
        val o = JSONObject()
            .put("ownerName", profile.ownerName)
            .put("contact", profile.contact)
            .put("deviceLabel", profile.deviceLabel)
        prefs.edit().putString(KEY, o.toString()).apply()
    }

    fun clear() {
        prefs.edit().remove(KEY).apply()
    }

    private companion object {
        const val KEY = "owner_profile"
    }
}

/** A plain-text ownership record the user can save or share. */
fun ownershipRecord(
    profile: OwnerProfile,
    device: PairedDevice?,
    connection: ConnectionStatus?,
    lastSeen: String,
): String = buildString {
    appendLine("DARK WEB LOCK — OWNERSHIP RECORD")
    appendLine("Generated by the owner's phone. Device facts are read from Android, not typed in.")
    appendLine()
    appendLine("Owner: ${profile.ownerName}")
    if (profile.contact.isNotBlank()) appendLine("Contact: ${profile.contact}")
    appendLine()
    if (device == null) {
        appendLine("No linked device.")
    } else {
        appendLine("Device label: ${profile.deviceLabel.ifBlank { device.alias ?: device.name ?: "(no name)" }}")
        appendLine("Name from device: ${device.name ?: "(none)"}")
        appendLine("Address: ${device.address}")
        appendLine("Type: ${device.type}")
        appendLine("Class: ${device.majorClass} / ${device.deviceClass}")
        device.services?.forEach { appendLine("Service: ${it.label}") }
        appendLine("Status now: ${connection?.summary ?: "unknown"}")
        appendLine("Last seen connected: $lastSeen")
    }
    appendLine()
    appendLine("Note: this is an ownership and evidence record only. It cannot block")
    appendLine("pairing or lock the earbuds; generic TWS earbuds expose no such control.")
}
